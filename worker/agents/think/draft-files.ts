/**
 * The Code tab's copy of the workspace files, rebuilt from SpaceDO when a draft's files change under it: a switch,
 * bringing in the live store's changes, or cancelling that. The rules for what it keeps live here, so they're tested.
 */
import type { FileState } from '../core/state';
import type { FileOutputType } from '../schemas';
import { decodeText } from '../../services/templates/snapshot';

/** Agent state goes to every open editor whole, so larger files stay out of the copy. */
export const MIRROR_MAX_BYTES = 256 * 1024;
/** What the whole copy may hold: it lives in the agent's state, one SQLite row with a limit near 2 MB. */
export const MIRROR_TOTAL_BYTES = 1024 * 1024;
/** Dependency lockfiles are large and no use in the Code tab. */
const LOCKFILE_NAMES: ReadonlySet<string> = new Set(['package-lock.json', 'bun.lock', 'bun.lockb', 'yarn.lock', 'pnpm-lock.yaml']);
/** Git's store, SpaceDO's bookkeeping and the host's own marker. */
const RESERVED_SEGMENTS: ReadonlySet<string> = new Set(['.git', '.afs', '.think']);
const FILE_PURPOSE = 'Generated by think';

export interface WorkspaceListing {
	path: string;
	size: number;
}

export interface MirroredFile {
	filePath: string;
	fileContents: string;
}

export interface MirrorRebuild {
	map: Record<string, FileState>;
	/** Display paths the editor drops. */
	removed: string[];
	/** Files the editor loads: new ones and ones whose text changed. */
	changed: FileOutputType[];
}

function displayPath(path: string): string {
	return path.replace(/^\/+/, '');
}

function isMirrorable(path: string): boolean {
	const segments = displayPath(path).split('/');
	return !segments.some((segment) => RESERVED_SEGMENTS.has(segment)) && !LOCKFILE_NAMES.has(segments[segments.length - 1]);
}

/** Workspace files worth reading for the copy, by path: outside reserved directories, not lockfiles, within the size cap. */
export function mirrorCandidates(listing: readonly WorkspaceListing[]): WorkspaceListing[] {
	return listing
		.filter(({ path, size }) => size <= MIRROR_MAX_BYTES && isMirrorable(path))
		.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}

/** The copy's entry for a file, under the path the editor shows; null for binary or oversized content. */
export function mirroredFile(path: string, bytes: Uint8Array): MirroredFile | null {
	if (bytes.byteLength > MIRROR_MAX_BYTES) return null;
	const text = decodeText(bytes);
	return text === null ? null : { filePath: displayPath(path), fileContents: text };
}

/**
 * The files the copy keeps, taken in path order while their text fits in the total. A file whose listed size is more
 * than what is left is skipped unread; a smaller one after it can still fit. The budget is spent by the decoded text's
 * byte length, so binary files, which the copy leaves out, cost nothing.
 */
export async function selectMirrorFiles(
	listing: readonly WorkspaceListing[],
	read: (path: string) => Promise<Uint8Array | null>,
	totalBytes: number = MIRROR_TOTAL_BYTES,
): Promise<MirroredFile[]> {
	const encoder = new TextEncoder();
	const files: MirroredFile[] = [];
	let remaining = totalBytes;
	for (const { path, size } of mirrorCandidates(listing)) {
		if (size > remaining) continue;
		const bytes = await read(path);
		const file = bytes ? mirroredFile(path, bytes) : null;
		if (!file) continue;
		const spent = encoder.encode(file.fileContents).byteLength;
		if (spent > remaining) continue;
		files.push(file);
		remaining -= spent;
	}
	return files;
}

/** The new copy, keeping each file's purpose, with what the editor has to drop and load to match it. */
export function rebuildMirror(previous: Readonly<Record<string, FileState>>, files: readonly MirroredFile[]): MirrorRebuild {
	const map: Record<string, FileState> = {};
	const changed: FileOutputType[] = [];
	for (const { filePath, fileContents } of files) {
		const before = previous[filePath];
		const file = { filePath, fileContents, filePurpose: before?.filePurpose || FILE_PURPOSE };
		map[filePath] = { ...file, lastDiff: '' };
		if (before?.fileContents !== fileContents) changed.push(file);
	}
	const removed = Object.keys(previous).filter((filePath) => !(filePath in map));
	return { map, removed, changed };
}
