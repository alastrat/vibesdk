import { describe, expect, it } from 'vitest';
import { MIRROR_MAX_BYTES, MIRROR_TOTAL_BYTES, mirrorCandidates, mirroredFile, rebuildMirror, selectMirrorFiles } from './draft-files';
import type { FileState } from '../core/state';

const text = (value: string) => new TextEncoder().encode(value);
const KIB = 1024;

/** Text of exactly `bytes` bytes, so a test controls the size the budget sees. */
const textOfSize = (bytes: number) => new Uint8Array(bytes).fill(0x61);

/** A workspace of in-memory files; `reads` records which paths were actually read, in order. */
function workspace(files: Record<string, Uint8Array>, listedSizes: Record<string, number> = {}) {
	const reads: string[] = [];
	const listing = Object.entries(files).map(([path, bytes]) => ({ path, size: listedSizes[path] ?? bytes.byteLength }));
	const read = async (path: string) => {
		reads.push(path);
		return files[path] ?? null;
	};
	return { listing, read, reads };
}

const totalBytesOf = (files: readonly { fileContents: string }[]) => files.reduce((sum, file) => sum + text(file.fileContents).byteLength, 0);

describe("the Code tab's copy of a draft", () => {
	it('reads the text files of a listing and leaves out bookkeeping and oversized files', () => {
		const listing = [
			{ path: '/index.html', size: 120 },
			{ path: '/src/app.tsx', size: 2_000 },
			{ path: '/public/logo.png', size: 4_000 },
			{ path: '/.git/HEAD', size: 20 },
			{ path: '/.afs/state.json', size: 50 },
			{ path: '/.think/space.json', size: 90 },
			{ path: '/public/catalog.json', size: MIRROR_MAX_BYTES + 1 },
		];
		expect(mirrorCandidates(listing).map(({ path }) => path)).toEqual(['/index.html', '/public/logo.png', '/src/app.tsx']);
	});

	it('leaves lockfiles out at any depth, but keeps files that only look like them', () => {
		const listing = [
			{ path: '/package-lock.json', size: 900 },
			{ path: '/bun.lock', size: 900 },
			{ path: '/bun.lockb', size: 900 },
			{ path: '/yarn.lock', size: 900 },
			{ path: '/pnpm-lock.yaml', size: 900 },
			{ path: '/apps/web/package-lock.json', size: 900 },
			{ path: '/packages/ui/pnpm-lock.yaml', size: 900 },
			{ path: '/package.json', size: 300 },
			{ path: '/docs/bun.lock.md', size: 100 },
			{ path: '/src/lockfile.ts', size: 100 },
		];
		expect(mirrorCandidates(listing).map(({ path }) => path)).toEqual(['/docs/bun.lock.md', '/package.json', '/src/lockfile.ts']);
	});

	it('mirrors text under its display path and leaves out binaries', () => {
		expect(mirroredFile('/src/app.tsx', text('export const App = 1;\n'))).toEqual({ filePath: 'src/app.tsx', fileContents: 'export const App = 1;\n' });
		expect(mirroredFile('/public/logo.png', new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x00, 0xff]))).toBeNull();
		expect(mirroredFile('/public/font.woff2', new Uint8Array([0x77, 0x4f, 0x46, 0x32, 0xc3]))).toBeNull();
		expect(mirroredFile('/big.txt', new Uint8Array(MIRROR_MAX_BYTES + 1).fill(0x61))).toBeNull();
	});

	it("replaces the copy with the draft's files, naming the files to drop and the ones to load", () => {
		const previous: Record<string, FileState> = {
			'index.html': { filePath: 'index.html', fileContents: '<h1>Main</h1>\n', filePurpose: 'Home page', lastDiff: '' },
			'about.html': { filePath: 'about.html', fileContents: 'About\n', filePurpose: 'Generated by think', lastDiff: '' },
			'sale.html': { filePath: 'sale.html', fileContents: 'Sale\n', filePurpose: 'Generated by think', lastDiff: '' },
		};
		const { map, removed, changed } = rebuildMirror(previous, [
			{ filePath: 'index.html', fileContents: '<h1>Spring sale</h1>\n' },
			{ filePath: 'about.html', fileContents: 'About\n' },
			{ filePath: 'banner.html', fileContents: 'Banner\n' },
		]);
		expect(Object.keys(map).sort()).toEqual(['about.html', 'banner.html', 'index.html']);
		expect(map['index.html']).toEqual({ filePath: 'index.html', fileContents: '<h1>Spring sale</h1>\n', filePurpose: 'Home page', lastDiff: '' });
		expect(removed).toEqual(['sale.html']);
		expect(changed.map((file) => file.filePath)).toEqual(['index.html', 'banner.html']);
		expect(changed[1]).toEqual({ filePath: 'banner.html', fileContents: 'Banner\n', filePurpose: 'Generated by think' });
	});
});

describe("the Code tab's copy stays under a total size", () => {
	it('never reads or keeps lockfiles', async () => {
		const { listing, read, reads } = workspace({
			'/package.json': text('{}\n'),
			'/package-lock.json': text('{"lockfileVersion": 3}\n'),
			'/apps/web/yarn.lock': text('# yarn\n'),
			'/src/app.tsx': text('export {}\n'),
		});
		const files = await selectMirrorFiles(listing, read);
		expect(files.map((file) => file.filePath)).toEqual(['package.json', 'src/app.tsx']);
		expect(reads).toEqual(['/package.json', '/src/app.tsx']);
	});

	it('takes files in path order, whatever order the listing came in', async () => {
		const { listing, read } = workspace({
			'/src/zeta.ts': text('z\n'),
			'/index.html': text('i\n'),
			'/src/Alpha.ts': text('A\n'),
			'/src/alpha.ts': text('a\n'),
			'/about.html': text('b\n'),
		});
		const files = await selectMirrorFiles([...listing].reverse(), read);
		expect(files.map((file) => file.filePath)).toEqual(['about.html', 'index.html', 'src/Alpha.ts', 'src/alpha.ts', 'src/zeta.ts']);
	});

	it('stops taking files once the total is reached, so the copy never exceeds the cap', async () => {
		const files: Record<string, Uint8Array> = {};
		for (const name of ['a', 'b', 'c', 'd', 'e', 'f']) files[`/src/${name}.txt`] = textOfSize(200 * KIB);
		const { listing, read } = workspace(files);
		const selected = await selectMirrorFiles(listing, read);
		expect(selected.map((file) => file.filePath)).toEqual(['src/a.txt', 'src/b.txt', 'src/c.txt', 'src/d.txt', 'src/e.txt']);
		expect(totalBytesOf(selected)).toBeLessThanOrEqual(MIRROR_TOTAL_BYTES);
		expect(MIRROR_TOTAL_BYTES).toBe(1024 * 1024);
	});

	it("skips a file that doesn't fit in what is left without reading it, and still takes a smaller later one", async () => {
		const { listing, read, reads } = workspace({
			'/a.txt': textOfSize(256 * KIB),
			'/b.txt': textOfSize(256 * KIB),
			'/c.txt': textOfSize(256 * KIB),
			'/d.txt': textOfSize(200 * KIB),
			'/e.txt': textOfSize(100 * KIB),
			'/f.txt': textOfSize(40 * KIB),
		});
		const selected = await selectMirrorFiles(listing, read);
		expect(selected.map((file) => file.filePath)).toEqual(['a.txt', 'b.txt', 'c.txt', 'd.txt', 'f.txt']);
		expect(reads).not.toContain('/e.txt');
		expect(totalBytesOf(selected)).toBe(768 * KIB + 200 * KIB + 40 * KIB);
	});

	it("counts the text's byte length once read, not the listed size or the character count", async () => {
		const accented = new TextEncoder().encode('\u00e9'.repeat(100 * KIB));
		const understated: Record<string, Uint8Array> = {};
		const listed: Record<string, number> = {};
		for (const name of ['a', 'b', 'c', 'd', 'e', 'f']) {
			understated[`/${name}.txt`] = accented;
			listed[`/${name}.txt`] = 1;
		}
		const { listing, read } = workspace(understated, listed);
		const selected = await selectMirrorFiles(listing, read);
		expect(totalBytesOf(selected)).toBeLessThanOrEqual(MIRROR_TOTAL_BYTES);
		expect(selected).toHaveLength(5);
	});

	it("doesn't spend the budget on binary files the copy leaves out", async () => {
		const png = new Uint8Array(250 * KIB).fill(0xff);
		const { listing, read } = workspace({
			'/a.png': png,
			'/b.png': png,
			'/c.png': png,
			'/d.png': png,
			'/src/one.txt': textOfSize(250 * KIB),
			'/src/two.txt': textOfSize(250 * KIB),
			'/src/three.txt': textOfSize(250 * KIB),
			'/src/four.txt': textOfSize(250 * KIB),
		});
		const selected = await selectMirrorFiles(listing, read);
		expect(selected.map((file) => file.filePath)).toEqual(['src/four.txt', 'src/one.txt', 'src/three.txt', 'src/two.txt']);
	});

	it('keeps leaving out files over the per-file cap, and a file that cannot be read', async () => {
		const { listing, read, reads } = workspace({
			'/big.txt': textOfSize(MIRROR_MAX_BYTES + 1),
			'/gone.txt': textOfSize(10),
			'/small.txt': textOfSize(10),
		});
		const selected = await selectMirrorFiles(
			listing,
			async (path) => (path === '/gone.txt' ? null : read(path)),
		);
		expect(selected.map((file) => file.filePath)).toEqual(['small.txt']);
		expect(reads).not.toContain('/big.txt');
	});
});

